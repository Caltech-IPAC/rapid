# footprint test: perimeter-order independence and RA wrap
# ---------------------------------------------------------------------------

def square_corners(ra, dec, half_deg):
    return [(ra - half_deg, dec - half_deg), (ra + half_deg, dec - half_deg),
            (ra + half_deg, dec + half_deg), (ra - half_deg, dec + half_deg)]


def test_contains_position_inside_and_outside():
    corners = square_corners(10.0, 20.0, 0.1)
    assert contains_position(10.0, 20.0, corners)
    assert contains_position(10.05, 20.08, corners)
    assert not contains_position(10.25, 20.0, corners)
    assert not contains_position(10.0, 20.15, corners)


def test_contains_position_corner_order_does_not_matter():
    # the DB promises no winding order; a zigzag ordering must still work
    c1, c2, c3, c4 = square_corners(10.0, 20.0, 0.1)
    assert contains_position(10.0, 20.0, [c1, c3, c2, c4])
    assert not contains_position(10.25, 20.0, [c1, c3, c2, c4])


def test_contains_position_across_ra_wrap():
    corners = [(359.95, -0.05), (0.05, -0.05), (0.05, 0.05), (359.95, 0.05)]
    assert contains_position(0.0, 0.0, corners)
    assert contains_position(359.97, 0.0, corners)
    assert not contains_position(0.2, 0.0, corners)


