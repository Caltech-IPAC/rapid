def make_position(aid, field=3, n_epochs=10):
    return {"aid": aid, "sid": aid, "field": field, "ra": 268.0 + aid * 1e-4,
            "dec": -29.9, "n_prv": 1, "n_triggers": 1, "n_epochs": n_epochs}


def test_choose_runs_dominant_field_and_history_spread():
    positions = ([make_position(i, field=3, n_epochs=i * 10)
                  for i in range(1, 8)]
                 + [make_position(100, field=4, n_epochs=5)])
    runs = choose_runs(positions, [1, 3, 99])
    assert [len(picks) for _, picks in runs] == [1, 3, 7]
    assert all(field == 3 for field, _ in runs)          # dominant field only
    # the single-position run takes a median-history object
    assert runs[0][1][0]["aid"] == 4
    # multi-position batches span the epoch-count range
    aids = [p["aid"] for p in runs[1][1]]
    assert aids[0] == 1 and aids[-1] == 7
    # duplicate effective sizes are dropped, oversize is clamped to the pool
    assert len(choose_runs(positions, [99, 7, 1])) == 2


def test_is_completed_run():
    # observed live: a mid-run S3 crash (1) and DB-unreachable (64) runs
    # fed the fit and produced a negative per-position cost
    assert is_completed_run({"exit_code": 0})
    assert is_completed_run({"exit_code": 62})       # warning, full output
    assert not is_completed_run({"exit_code": 1})    # python crash
    assert not is_completed_run({"exit_code": 64})   # catastrophic error
    assert not is_completed_run({"exit_code": 255})  # DB error
    assert not is_completed_run({"exit_code": None}) # timeout


def test_sample_evenly():
    items = list(range(100))
    sample = sample_evenly(items, 10)
    assert len(sample) == 10
    assert sample[0] == 0 and sample[-1] == 90       # spans the range
    assert sample == sorted(set(sample))             # unique, ordered
    assert sample_evenly(items, 200) == items        # short list untouched
    assert sample_evenly(items, None) == items       # no limit
    assert sample_evenly(items, 0) == items          # 0 = all


def test_fit_linear():
    slope, intercept = fit_linear([1, 4, 16], [5.0, 11.0, 35.0])
    assert slope == pytest.approx(2.0)
    assert intercept == pytest.approx(3.0)
    assert fit_linear([4, 4], [10.0, 12.0]) is None      # need 2 distinct x


