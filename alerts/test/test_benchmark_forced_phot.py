def make_summary(with_fit=True):
    return {
        "kind": "summary", "n_sources": 12, "n_objects": 9,
        "n_unassociated": 2, "epochs_median": 40, "epochs_p95": 80,
        "epochs_max": 90, "epochs_total": 400, "prv_median": 3, "prv_max": 8,
        "fields": {"3": {"n_objects": 9, "job_epochs": 120}},
        "runs": [{"field": 3, "n_positions": 1, "n_epochs": 100,
                  "wall_s": 5.0, "exit_code": 0, "staged_bytes": 2 ** 30},
                 {"field": 3, "n_positions": 16, "n_epochs": 100,
                  "wall_s": 35.0, "exit_code": 0, "staged_bytes": 2 ** 30}],
        "fit_fixed_s": 3.0 if with_fit else None,
        "fit_per_position_s": 2.0 if with_fit else None,
    }


def test_summary_lines_decision_aid():
    text = "\n".join(fp_summary_lines(make_summary()))
    assert "fixed 3.0 s per job + 2.0 s per position" in text
    assert "decision aid:" in text
    assert "~5.0 s added latency per alert" in text      # fixed + marginal
    assert "full re-run of this field" in text


def test_summary_lines_survey_only():
    summary = make_summary(with_fit=False)
    summary["runs"] = []
    text = "\n".join(fp_summary_lines(summary))
    assert "survey only" in text
    assert "decision aid:" not in text


def test_report_smoke(tmp_path, capsys):
    path = tmp_path / "fp.jsonl"
    meta = {"kind": "meta", "started_utc": "2026-07-24T00:00:00+00:00",
            "host": "x", "arch": "aarch64", "pid": 338173, "mode": "survey"}
    with open(path, "w") as f:
        for record in (meta, make_summary()):
            f.write(json.dumps(record) + "\n")
    report([str(path)])
    out = capsys.readouterr().out
    assert "pid=338173" in out
    assert "decision aid:" in out
