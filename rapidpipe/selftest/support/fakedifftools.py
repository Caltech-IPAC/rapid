"""Fake external tools for the difference stage, and a synthetic input set.

``FakeToolRunner`` stands in for :class:`rapidpipe.science.difference.tools.ToolRunner`:
it recognises each command the stage issues (SExtractor ``sex``, SWarp
``swarp``, ``bkgest``, ``py_zogy.py``, and the SFFT shell command) and
writes plausible outputs with numpy and astropy, so the whole stage can
run with no C tools, no ZOGY and no SFFT installed. The outputs are not
the tools' science; they are shaped like it (same files, same headers,
same catalog columns), which is what the stage's own logic needs. Every
call is recorded for assertions.

``fake_psf_catalog`` stands in for
:func:`rapidpipe.science.difference.psfcat.psf_catalog` (photutils).

``build_input_set`` writes a small synthetic input set -- a two-HDU
science image with a SIP WCS, a reference bundle on the same sky, the
reference catalog, two PSFs -- and its input-set manifest. The fixture
under ``tests/fixtures/difference/`` (and its packaged copy,
``rapidpipe/selftest/fixtures/difference/``, read by ``rapidpipe
selftest``) is generated by the same function.

Packaged under ``rapidpipe.selftest.support`` (not ``tests/``, which the
pipeline image excludes at build time -- ``containers/rapid-pipeline/
build.sh``) so ``rapidpipe selftest --stage difference`` can import it
inside the image. ``tests/unit/fakedifftools.py`` re-exports this module
for the test suite and for ``RAPIDPIPE_DIFFERENCE_TOOLKIT=tests.unit.
fakedifftools:fake_toolkit``.
"""

