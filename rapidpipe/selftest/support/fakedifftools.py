def build_input_set(inputs_dir: Path, *, seed: int = 20260922, rfid: int | None = None,
                    ref_infobits: int = 0, gzip_science: bool = True) -> Path:
    """Write the synthetic inputs and their input-set manifest; return the manifest path."""
    rng = np.random.default_rng(seed)
    inputs_dir.mkdir(parents=True, exist_ok=True)
    (inputs_dir / "l2").mkdir(exist_ok=True)
    (inputs_dir / "ref").mkdir(exist_ok=True)
    (inputs_dir / "psf").mkdir(exist_ok=True)

    # Science: DN in HDU 1, 64x64, dev's socsims layout.
    sci = _sky(NAXIS, STARS + (TRANSIENT,), rng, background=100.0 * EXPTIME / 10, noise=5.0)
    sci_header = wcs_header(NAXIS, sip=True)
    sci_header["EXPTIME"] = EXPTIME
    sci_header["ZPTMAG"] = ZPTMAG
    sci_header["SCA-NUM"] = 7
    science_path = inputs_dir / "l2" / (SCIENCE_NAME if gzip_science else SCIENCE_NAME[:-3])
    fits.HDUList([fits.PrimaryHDU(), fits.ImageHDU(data=sci.astype(np.float32),
                                                   header=sci_header)]).writeto(science_path)

    # Reference bundle on the 65x65 grid the reformatted science image has.
    n = NAXIS + 1
    # DN/s, the science stars without the transient.
    ref = _sky(n, tuple((x, y, f / EXPTIME) for x, y, f in STARS), rng, background=0.0, noise=0.02)
    ref_header = wcs_header(n, sip=False)
    ref_header["MAGZP"] = 17.0
    ref_image = inputs_dir / "ref" / "awaicgen_output_mosaic_image.fits"
    fits.PrimaryHDU(data=ref.astype(np.float32), header=ref_header).writeto(ref_image)
    ref_cov = inputs_dir / "ref" / "awaicgen_output_mosaic_cov_map.fits"
    cov = np.full((n, n), 5.0, dtype=np.float32)
    cov[:, :3] = 0.0            # an uncovered strip the coverage mask must blank
    fits.PrimaryHDU(data=cov, header=ref_header).writeto(ref_cov)
    ref_unc = inputs_dir / "ref" / "awaicgen_output_mosaic_uncert_image.fits"
    fits.PrimaryHDU(data=np.full((n, n), 0.02, dtype=np.float32), header=ref_header).writeto(ref_unc)
    ref_cat = inputs_dir / "ref" / "awaicgen_output_mosaic_refimsexcat.txt"
    params = _params(str(CDF_DIR / "rapidSexParamsRefImage.inp"))
    ref_cat.write_text(
        "".join(f"#{i + 1:4d} {p}\n" for i, p in enumerate(params))
        + "".join(" ".join(_catalog_row(p, int(x), int(y), flux) for p in params) + "\n"
                  for x, y, flux in STARS))

    # PSFs: 9x9 Gaussians.
    sci_psf = inputs_dir / "psf" / "sciimage_psf_f184_sca07.fits"
    fits.PrimaryHDU(data=(3.0 * _gaussian(9, 4, 4)).astype(np.float32)).writeto(sci_psf)
    ref_psf = inputs_dir / "psf" / "refimage_psf_f146_sca07.fits"
    psf = _gaussian(9, 4, 4)
    fits.PrimaryHDU(data=(psf / psf.sum()).astype(np.float32)).writeto(ref_psf)

    manifest = {
        "schema_version": "1",
        "run": "01J8Y6QZ3MA2B4C6D8E0F2G2RN",
        "unit": {"kind": "detector-image", "id": "e20260821001234/SCA07"},
        "stage": "input-set",
        "attempt": "01J8Y6QZ3MA2B4C6D8E0F2G2AT",
        "execution_record": "exec/input-set.json",
        "inputs": {"manifest": "input-set", "products": {}, "result_sets": []},
        "outputs": [
            {"kind": "l2-image", "format_version": "1", "instance": L2_INSTANCE,
             "key": {"exposure": "e20260821001234", "detector": "7", "version": "1"},
             "primary": _member("image", science_path, inputs_dir)["path"],
             "members": [_member("image", science_path, inputs_dir)],
             "registration": _l2_registration()},
            {"kind": "reference-image", "format_version": "1", "instance": REF_INSTANCE,
             "key": {"field": "5321", "filter": "F184", "recipe": "awaicgen", "version": "1"},
             "primary": _member("image", ref_image, inputs_dir)["path"],
             "members": [_member("image", ref_image, inputs_dir),
                         _member("coverage", ref_cov, inputs_dir),
                         _member("uncertainty", ref_unc, inputs_dir)],
             "registration": {"infobits": ref_infobits, "rfid": rfid}},
            {"kind": "reference-catalog", "format_version": "1", "instance": REFCAT_INSTANCE,
             "key": {"reference": REF_INSTANCE, "catalog_type": "sextractor"},
             "primary": _member("catalog", ref_cat, inputs_dir)["path"],
             "members": [_member("catalog", ref_cat, inputs_dir)], "registration": {}},
            {"kind": "psf", "format_version": "1", "instance": SCI_PSF_INSTANCE,
             "key": {"filter": "F184", "detector": "7", "version": "1", "applies_to": "science"},
             "primary": _member("psf", sci_psf, inputs_dir)["path"],
             "members": [_member("psf", sci_psf, inputs_dir)], "registration": {}},
            {"kind": "psf", "format_version": "1", "instance": REF_PSF_INSTANCE,
             "key": {"filter": "F184", "detector": "7", "version": "1", "applies_to": "reference"},
             "primary": _member("psf", ref_psf, inputs_dir)["path"],
             "members": [_member("psf", ref_psf, inputs_dir)], "registration": {}},
        ],
    }
    if gzip_science:
        import gzip
        raw = science_path.read_bytes()
        science_path.write_bytes(gzip.compress(raw, mtime=0))
        manifest["outputs"][0]["members"] = [_member("image", science_path, inputs_dir)]
    manifest_path = inputs_dir / "manifest.json"
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n")
    return manifest_path


